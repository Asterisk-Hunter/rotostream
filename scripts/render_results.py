"""Generate the published results table directly from evaluator JSON artifacts."""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BENCHMARKS = ROOT / "reports" / "benchmarks"


def read(name: str) -> dict:
    result = json.loads((BENCHMARKS / name).read_text(encoding="utf-8"))
    if result["config"]["protocol"] != "davis" or not result["config"]["is_full_split"]:
        raise ValueError(f"{name} is not a complete DAVIS protocol run")
    if result["n_sequences"] != 30 or result["n_object_tracks"] != 61:
        raise ValueError(f"{name} has unexpected DAVIS 2017 val coverage")
    if not all(math.isfinite(result[key]) and 0 <= result[key] <= 1 for key in ("j", "f", "jf")):
        raise ValueError(f"{name} has invalid scores")
    return result


def main() -> None:
    neural = read("davis2017_val_sam2_tiny.json")
    baseline = read("davis2017_val_naive.json")
    rows = []
    for label, result in (("Color baseline", baseline), ("SAM 2.1 Hiera-T memory reproduction", neural)):
        rows.append(f"| {label} | {result['j'] * 100:.2f} | {result['f'] * 100:.2f} | {result['jf'] * 100:.2f} | {result['config']['timings']['propagation_fps']:.2f} |")
    config = neural["config"]
    worst = sorted(neural["sequences"], key=lambda item: item["jf"])[:8]
    weakest_rows = "\n".join(
        f"| `{item['name']}` | {item['j'] * 100:.2f} | {item['f'] * 100:.2f} | {item['jf'] * 100:.2f} |"
        for item in worst
    )
    ablations_path = BENCHMARKS / "synthetic_ablations.json"
    causality = ""
    causality_path = BENCHMARKS / "neural_causality.json"
    if causality_path.exists():
        evidence = json.loads(causality_path.read_text(encoding="utf-8"))
        checks = [check for report in evidence["reports"] for check in report["checks"]]
        if not evidence["passed"] or len(evidence["reports"]) != 10 or len(checks) != 30:
            raise ValueError("neural causality evidence is incomplete or failed")
        if any(check["differing_pixels"] for check in checks):
            raise ValueError("neural causality evidence contains changed masks")
        causality = f"""
## Causality probes

[`neural_causality.json`](../reports/benchmarks/neural_causality.json) records
30 exact-mask probes over all five synthetic scenarios in both directions.
Replacing unvisited frames with deterministic noise changed zero pixels at every
probe. This run used `{evidence['precision']}` autocast on `{evidence['device']}`,
with a reset before each sweep. These sampled probes complement the contract tests;
they do not establish correctness for every possible clip or prompt policy.
"""
    ablations = ""
    if ablations_path.exists():
        payload = json.loads(ablations_path.read_text(encoding="utf-8"))
        if len(payload["runs"]) != 8:
            raise ValueError("the ablation run is incomplete")
        default = next(row["evaluation"]["jf"] for row in payload["runs"] if row["name"] == "memory_6")
        ablation_rows = "\n".join(
            f"| `{row['name']}` | {row['evaluation']['jf']:.4f} | {row['evaluation']['jf'] - default:+.4f} |"
            for row in payload["runs"]
        )
        ablations = f"""
## Synthetic component regressions

These author-created toy clips test wiring and component sensitivity. They are
not evidence of real-world quality, and they do not belong in a resume headline.
Each row uses the same released weights, one interior click, causal propagation,
and the same five synthetic clips. Precision is `{payload.get('precision', 'float32')}`
on `{payload['device']}`; these rows are not mixed with full-precision DAVIS results.
The memory budget counts recent frames in
addition to the prompted frame; offsets beyond the released positional table
saturate. Disabling a component without retraining is an inference intervention.

| Variant | J&F (fraction) | Delta from memory 6 |
| --- | --- | --- |
{ablation_rows}

Source: [`synthetic_ablations.json`](../reports/benchmarks/synthetic_ablations.json).
"""
    document = f"""# Measured results

Generated by `python scripts/render_results.py` from the checked-in evaluator
artifacts. Scores are percentages in the DAVIS table and fractions in raw JSON.
Measured on {neural['created_at'][:10]}.

## DAVIS 2017 validation

**30 clips, 61 object tracks, {neural['n_frames']:,} scored object-frames.** Both
trackers receive the first frame's ground-truth mask, propagate forward, and score
frames 1 through T−2. J and F are averaged per object track, then over all 61 tracks.
Each object is tracked independently; overlapping predictions are not arbitrated
into a joint multi-object label map. This is an independent-object reproduction
evaluation, not an official joint segmentation leaderboard submission.

| Tracker | J | F | J&F | Propagation FPS |
| --- | --- | --- | --- | --- |
{chr(10).join(rows)}

The improvement is {(neural['jf'] - baseline['jf']) * 100:.2f} J&F points under the
same quality protocol. FPS excludes weights, prompts, dataset loading and metrics.
The neural run used `{config['gpu']}`, `{config['torch_version']}`, transformers
`{config['transformers_version']}`, full-precision inference and a {config['working_resolution']}px
encoder. Masks are scored at DAVIS 480p source resolution. The baseline ran on CPU;
its speed is not a hardware-controlled comparison. Neural wall time was
{neural['elapsed_s'] / 60:.1f} minutes, including loading and scoring.

Released weights: `{config['weights_id']}`, revision
`{config['weights_revision']}`. No DAVIS fine-tuning was performed. These numbers
must not be compared directly with Hiera-B+/L paper results or one-click results.
The raw reports retain their original Git revision and `git_dirty=true`; the
measurement occurred during this implementation pass, before its final commits.

- [Neural JSON](../reports/benchmarks/davis2017_val_sam2_tiny.json) and [CSV](../reports/benchmarks/davis2017_val_sam2_tiny.csv)
- [Baseline JSON](../reports/benchmarks/davis2017_val_naive.json) and [CSV](../reports/benchmarks/davis2017_val_naive.csv)

### Lowest-scoring neural tracks

The average hides failure cases. These are the eight weakest object tracks,
selected directly from the neural report; they identify useful footage for a
follow-up occlusion, identity-switch and prompt-error review. Scores alone do not
establish the cause of a failure.

| Object track | J | F | J&F |
| --- | --- | --- | --- |
{weakest_rows}

## Module parity and training

[`sam2_tiny_parity.json`](../reports/benchmarks/sam2_tiny_parity.json) checks released
weight compatibility, memory features/positions, conditioned features, single and
multimask decoder logits, quality scores, presence logits, selected pointer tokens,
and visible/absent memory writes. Zero missing/unexpected keys; all checks pass
at absolute and relative tolerance 1e-5. Memory encoder and decoder outputs are exact on
these probes; memory attention differs by at most 7.153e-7. Reference decoder
attention uses eager kernels to align the numerical comparison. This is module
parity, not proof that every tracking policy is identical to the reference.

[`neural_training_dryrun.txt`](../reports/benchmarks/neural_training_dryrun.txt)
records three two-frame backward passes with finite loss and nonzero gradients in
272 of 305 trainable tensors. The encoder remains frozen. It establishes gradient
wiring, not convergence, generalization or a real-data training result. Checkpoints
use tensor-only loading; trained-stack loading restores the released frozen encoder.
{ablations}
{causality}
## Reproduce

```bash
cd ml
python -m rotostream_ml.evaluate --model sam2_memory --dataset davis --root ../datasets/DAVIS --split val --resolution 480p --protocol davis --prompt-mode mask --device cuda --json ../runs/davis_val.json --csv ../runs/davis_val.csv
python -m rotostream_ml.evaluate --model naive --dataset davis --root ../datasets/DAVIS --split val --resolution 480p --protocol davis --prompt-mode mask --device cpu --json ../runs/davis_baseline.json
python -m rotostream_ml.ablations --device cuda --precision bfloat16 --json ../runs/synthetic_ablations.json
python -m rotostream_ml.leakcheck --model sam2_memory --device cuda --precision bfloat16 --all --max-checks 3 --json ../runs/causality.json
```

Install the model dependencies and download the official dataset before evaluation.
The loader prefers the explicit 2017 split and rejects ambiguous full benchmark
requests. Diagnostic `--prompt-frame` and `--bidirectional` runs use a different
protocol and must be labeled separately. Bidirectional means two causal sweeps,
not attention to unvisited frames.
"""
    (ROOT / "docs" / "RESULTS.md").write_text(document, encoding="utf-8")
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    start, end = "<!-- benchmark:start -->", "<!-- benchmark:end -->"
    before, remainder = readme.split(start, 1)
    _, after = remainder.split(end, 1)
    table = "| Tracker | J | F | J&F |\n| --- | --- | --- | --- |\n"
    for label, result in (("Color baseline", baseline), ("SAM 2.1 Hiera-T memory reproduction", neural)):
        table += f"| {label} | {result['j'] * 100:.2f} | {result['f'] * 100:.2f} | {result['jf'] * 100:.2f} |\n"
    readme_path.write_text(before + start + "\n" + table + end + after, encoding="utf-8")
    print("Updated docs/RESULTS.md from measured artifacts")


if __name__ == "__main__":
    main()
